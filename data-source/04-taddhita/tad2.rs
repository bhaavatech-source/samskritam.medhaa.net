// stdin: id \t base(slp1) \t Taddhita \t linga(m|f|n|stem) \t artha(optional, TaddhitaArtha name or -)
// stdout: same + \t stems(|) \t nominative singular(|) ; unknown taddhita/artha -> "?"
use std::io::BufRead;
use vidyut_prakriya::args::*;
use vidyut_prakriya::Vyakarana;
fn main() {
    let v = Vyakarana::new();
    for line in std::io::stdin().lock().lines() {
        let line = line.unwrap(); let f: Vec<&str> = line.split('\t').collect();
        let t = match Taddhita::iter().find(|k| format!("{:?}", k) == f[2]) { Some(t) => t, None => { println!("{line}\t?\t?"); continue; } };
        let p = Pratipadika::basic(Slp1String::from(f[1]).unwrap());
        let mut b = Taddhitanta::builder(); b.pratipadika(p).taddhita(t);
        if f.len() > 4 && f[4] != "-" {
            match artha_from(f[4]) { Some(a) => { b.artha(a); }, None => { println!("{line}\t?artha\t?"); continue; } }
        }
        let td = match b.build() { Ok(x) => x, Err(_) => { println!("{line}\t!\t!"); continue; } };
        let mut s: Vec<String> = v.derive_taddhitantas(&td).iter().map(|x| x.text()).collect(); s.sort(); s.dedup();
        let mut nom = vec![];
        if f[3] != "stem" {
            let l = match f[3] { "m" => Linga::Pum, "f" => Linga::Stri, _ => Linga::Napumsaka };
            for p in v.derive_subantas(&Subanta::new(td.clone(), l, Vibhakti::Prathama, Vacana::Eka)) { nom.push(p.text()); }
        }
        nom.sort(); nom.dedup();
        println!("{line}\t{}\t{}", s.join("|"), nom.join("|"));
    }
}

